#include "printf.h"

void	ft_putnbr(int n)
{
	if (n < 0)
	{
		if (n == INT_MIN)
		{
			write (fd, "-2147483648", 11);
			return ;
		}
		write (1, "-", 1);
		n *= -1;
	}
	if (n > 9)
		ft_putnbr(n / 10);
	write (1, &"0123456789"[n % 10], 1);
}